import type { Agency, ContentItem, Country, DirectoryEntry } from "@dadalink/domain"
import { Effect } from "effect"
import { Database } from "./Database.ts"
import { agencyRow, contentItemRow, contentTranslationRows, directoryEntryRow } from "./repos/CatalogWriterDrizzle.ts"
import { agencies, contentItems, contentTranslations, directoryEntries } from "./schema/index.ts"

export interface CatalogSeedInput {
  readonly items: ReadonlyArray<ContentItem>
  readonly directory: ReadonlyArray<{ readonly country: Country; readonly entries: ReadonlyArray<DirectoryEntry> }>
  readonly agencies: ReadonlyArray<Agency>
}

/** Renders a bound parameter as a SQLite literal. */
export const sqlLiteral = (value: unknown): string => {
  if (value === null || value === undefined) return "NULL"
  if (typeof value === "boolean") return value ? "1" : "0"
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Cannot render ${value} as SQL`)
    return String(value)
  }
  if (typeof value === "bigint") return value.toString()
  if (typeof value === "string") return `'${value.replaceAll("'", "''")}'`
  return sqlLiteral(JSON.stringify(value))
}

/** Inlines `?` placeholders (drizzle never emits `?` elsewhere in insert statements). */
const inline = (query: { readonly sql: string; readonly params: ReadonlyArray<unknown> }): string => {
  let index = 0
  return query.sql.replace(/\?/g, () => sqlLiteral(query.params[index++]))
}

const clear = (table: string, where?: string) => `DELETE FROM ${table}${where === undefined ? "" : ` WHERE ${where}`};`

/**
 * SQL statements that replace the catalogue, for targets where the loader
 * cannot run in-process (D1). Uses the same row mappers as
 * `CatalogWriterDrizzle`; FTS stays in sync via triggers. Requires a
 * `Database` only to build statements; nothing is executed.
 */
export const catalogSeedStatements = Effect.fn("catalogSeedStatements")(function* (input: CatalogSeedInput) {
  const db = yield* Database
  const statements: Array<string> = [clear("content_translations"), clear("content_items")]
  for (const item of input.items) {
    statements.push(`${inline(db.insert(contentItems).values(contentItemRow(item)).toSQL())};`)
    for (const row of contentTranslationRows(item)) {
      statements.push(`${inline(db.insert(contentTranslations).values(row).toSQL())};`)
    }
  }
  for (const { country, entries } of input.directory) {
    statements.push(clear("directory_entries", `country = ${sqlLiteral(country)}`))
    for (const [position, entry] of entries.entries()) {
      statements.push(`${inline(db.insert(directoryEntries).values(directoryEntryRow(entry, position)).toSQL())};`)
    }
  }
  statements.push(clear("agencies"))
  for (const agency of input.agencies)
    statements.push(`${inline(db.insert(agencies).values(agencyRow(agency)).toSQL())};`)
  return statements as ReadonlyArray<string>
})

/** The statements as one script for `wrangler d1 execute DB --local --file <script>`. */
export const catalogSeedSql = (input: CatalogSeedInput) =>
  Effect.map(
    catalogSeedStatements(input),
    (statements) => `-- Generated by the DadaLink content loader. Replaces the catalogue.\n${statements.join("\n")}\n`
  )
