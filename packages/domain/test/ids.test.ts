import { describe, expect, it } from "@effect/vitest"
import { Schema } from "effect"
import { AgencyId, ContentId, DeviceId, DirectoryEntryId, TelegramChatId } from "../src/index.ts"

describe("ContentId", () => {
  it("accepts lower-case slugs with dashes and slashes", () => {
    expect(Schema.decodeUnknownSync(ContentId)("abroad/isolation-and-loneliness")).toBe(
      "abroad/isolation-and-loneliness"
    )
    expect(Schema.decodeUnknownSync(ContentId)("rights-sa")).toBe("rights-sa")
  })

  it("rejects spaces, upper case and empty strings", () => {
    for (const bad of ["", "Has Space", "UPPER", "-leading", "trailing/"]) {
      expect(() => Schema.decodeUnknownSync(ContentId)(bad), bad).toThrow()
    }
  })
})

describe("DirectoryEntryId and AgencyId", () => {
  it("share the slug format", () => {
    expect(Schema.decodeUnknownSync(DirectoryEntryId)("sa-embassy-riyadh")).toBe("sa-embassy-riyadh")
    expect(Schema.decodeUnknownSync(AgencyId)("et-agency-001")).toBe("et-agency-001")
    expect(() => Schema.decodeUnknownSync(AgencyId)("Bad Id")).toThrow()
  })
})

describe("DeviceId", () => {
  it("must be a UUID generated by the client", () => {
    const id = "6f1c1d2e-8a3b-4c5d-9e6f-7a8b9c0d1e2f"
    expect(Schema.decodeUnknownSync(DeviceId)(id)).toBe(id)
    expect(() => Schema.decodeUnknownSync(DeviceId)("device-1")).toThrow()
  })
})

describe("TelegramChatId", () => {
  it("is an integer (negative for groups)", () => {
    expect(Schema.decodeUnknownSync(TelegramChatId)(123456)).toBe(123456)
    expect(Schema.decodeUnknownSync(TelegramChatId)(-100123)).toBe(-100123)
    expect(() => Schema.decodeUnknownSync(TelegramChatId)(1.5)).toThrow()
  })
})
